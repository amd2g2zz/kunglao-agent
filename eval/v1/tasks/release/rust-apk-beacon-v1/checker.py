#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""checker.py — rust-so-crack-v1 mechanical checker shim.

Standalone entry (the family is not in the shared family registry: fresh
probes are minted through the same-crate HOST oracle target/crackme_host,
not recomputed from a seed model). Emission contract mirrors
scripts/eval_checker.py exactly:

    METRIC <name>=<value>       (eval_dataset.metric_line)
    FAILURE code=<c> detail=...
    EVIDENCE <path>             the archived evidence JSON
    VERDICT PASS|FAIL|SKIP|REFUSED        (terminal; LAST wins)

Exit: 0 PASS · 1 FAIL · 2 REFUSED (bad task/candidate) · 3 SKIP
(crackme_host absent/non-executable — a host-oracle family degrades to a
structured SKIP, never a false FAIL).

Faces (armed per task.yaml `checker.oracles`):
  constant-hit     static: the candidate source must carry the graded
                   constants (sigma word / sbox seed / magic hex);
  replay-roundtrip reproduction: the candidate module (verify + probe)
                   must reproduce every published AND checker-minted
                   probe byte-exact — minted inputs derive from the task
                   seed, expected outputs stay checker-side (crackme_host
                   only), so digest-table copying of the published pairs
                   fails by construction.

Default candidate is the unit's reference.py (self-check); pass
--candidate to grade an arm's re-implementation.

stdlib only (plus the repo's eval_dataset/eval_checker helpers for the
shared protocol shapes).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import time
from pathlib import Path

_HERE = Path(__file__).resolve().parent
# corpus-mounted units reach this file via symlink; a fixed parents[4]
# resolves to the corpus root (no scripts/ there). Walk UP from BOTH the
# resolved and the invoked path until scripts/eval_checker.py exists.
_SCRIPTS = None
_probe = Path(__file__).parent
for _base in (_probe, _HERE, *_HERE.parents):
    for _sub in ("scripts", ".local_repo_link/scripts"):
        _cand = _base / _sub / "eval_checker.py"
        if _cand.is_file():
            _SCRIPTS = _base / _sub
            break
    if _SCRIPTS is not None:
        break
if _SCRIPTS is None:
    raise SystemExit("checker: cannot locate scripts/eval_checker.py "
                     "from " + str(_HERE))
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))

import eval_checker  # noqa: E402  (static_face reuse — same protocol)
import eval_dataset as ds  # noqa: E402

RC_PASS, RC_FAIL, RC_REFUSED, RC_SKIP = 0, 1, 2, 3

LINE_JSON = __import__("re").compile(r"^\s*\{.*\}\s*$")

# candidate seam (the #236 control-arm surface, per task.yaml contract)
CANDIDATE_SUFFIX = ".py"
CANDIDATE_ENTRIES = ("verify", "probe")

# minted probe shape: deterministic SplitMix64 streams off the task seed;
# lengths cycle a schedule — fresh inputs never stored anywhere
_MINT_LENGTHS = (17, 23, 31, 16, 40, 19, 28, 33)
_M64 = (1 << 64) - 1

_HARNESS = '''\
"""kunglao-eval replay harness (rust-so-crack face) — generated by checker.py."""
import json
import sys

# exec-compile load: the #863 Family-B confinement pins importlib spec
# loading to four sanctioned hosts; a corpus checker is not one.
_ns = {}
exec(compile(open(sys.argv[1], encoding="utf-8").read(),
             sys.argv[1], "exec"), _ns)
with open(sys.argv[2], encoding="utf-8") as fh:
    probes = json.load(fh)
for p in probes["probes"]:
    v = _ns['verify'](bytes(p["input"]))
    out = _ns['probe'](bytes(p["input"]))
    print(json.dumps({"i": p["i"], "verify": v, "probe": out}))
'''


class Refusal(Exception):
    def __init__(self, code: str, detail: str):
        super().__init__(detail)
        self.code = code
        self.detail = detail


class Skip(Exception):
    pass


class SplitMix64:
    def __init__(self, seed: int):
        self.s = (seed ^ 0x9E3779B97F4A7C15) & _M64

    def next(self) -> int:
        self.s = (self.s + 0x9E3779B97F4A7C15) & _M64
        z = self.s
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & _M64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & _M64
        return z ^ (z >> 31)


def minted_inputs(seed: int, count: int) -> list[bytes]:
    """Deterministic fresh inputs (length schedule cycles; every byte from
    the SplitMix64 stream)."""
    rng = SplitMix64(seed)
    out: list[bytes] = []
    for k in range(count):
        n = _MINT_LENGTHS[k % len(_MINT_LENGTHS)]
        buf = bytearray()
        while len(buf) < n:
            buf += rng.next().to_bytes(8, "little")
        out.append(bytes(buf[:n]))
    return out


# --------------------------------------------------------------- unit load
def load_unit() -> tuple[dict, dict]:
    task = ds.load_task(_HERE)
    ok, errors = ds.validate_task(task)
    if not ok:
        raise Refusal("BAD_TASK", f"{_HERE.name}: {'; '.join(errors)}")
    gt_path = _HERE / task["ground_truth"]["file"]
    if not gt_path.is_file():
        raise Refusal("BAD_TASK", f"ground truth missing: {gt_path}")
    gt = json.loads(gt_path.read_text(encoding="utf-8"))
    if gt.get("schema") != "kunglao-eval-ground-truth/1":
        raise Refusal("BAD_TASK",
                      f"ground truth schema {gt.get('schema')!r}")
    return task, gt


def validate_candidate(path: Path) -> None:
    if not path.is_file():
        raise Refusal("BAD_CANDIDATE", f"candidate not found: {path}")
    if path.suffix != CANDIDATE_SUFFIX:
        raise Refusal(
            "BAD_CANDIDATE",
            f"family rust-so-crack needs a {CANDIDATE_SUFFIX} candidate, "
            f"got {path.suffix}")


# ------------------------------------------------------------- host oracle
def host_expected(host: Path, inputs: dict[int, bytes]) -> dict[int, dict]:
    """Fresh probe outputs minted by the same-crate host oracle
    (held_out). Any failure to run degrades to SKIP, never FAIL."""
    if not (host.is_file() and host.stat().st_mode & 0o111):
        raise Skip(f"crackme_host oracle not executable: {host}")
    stdin_text = "".join(
        json.dumps({"i": i, "input": list(b)}) + "\n"
        for i, b in sorted(inputs.items()))
    try:
        proc = subprocess.run([str(host), "replay"], input=stdin_text,
                              capture_output=True, text=True, timeout=180)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise Skip(f"crackme_host replay failed: {exc}") from exc
    if proc.returncode != 0:
        raise Skip(f"crackme_host replay rc={proc.returncode}: "
                   f"{proc.stderr.strip()[:200]}")
    rows: dict[int, dict] = {}
    for line in proc.stdout.splitlines():
        if not LINE_JSON.match(line):
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row.get("i"), int):
            rows[row["i"]] = {"verify": row.get("verify"),
                              "probe": row.get("probe")}
    missing = [i for i in inputs if i not in rows]
    if missing:
        raise Skip(f"crackme_host replay missing rows: {missing}")
    return rows


# ---------------------------------------------------------------- replay
def _grade(probes: list[dict],
           expected: dict[int, dict],
           got: dict[int, tuple]) -> int:
    matched = 0
    for p in probes:
        pair = got.get(p["i"])
        if pair is None:
            continue
        want = expected[p["i"]]
        if pair[0] == want["verify"] and pair[1] == want["probe"]:
            matched += 1
    return matched


def _parse_rows(stdout: str) -> dict[int, tuple]:
    """Candidate harness stdout -> {probe id: (verify, probe)}."""
    got: dict[int, tuple] = {}
    for line in stdout.splitlines():
        if not LINE_JSON.match(line):
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row.get("i"), int):
            got[row["i"]] = (row.get("verify"), row.get("probe"))
    return got


def _candidate_replay(candidate: Path, probes: list[dict],
                      expected: dict[int, dict],
                      outdir: Path) -> tuple[int, int, float, list[dict]]:
    """Drive the candidate module over the probe set through a generated
    harness; returns (matched, count, ttc, failure notes)."""
    outdir = outdir.resolve()
    probes_file = outdir / f"probes-{_HERE.name}.json"
    payload = {"schema": "kunglao-eval-probes/1",
               "task_id": _HERE.name, "probes": probes}
    probes_file.write_text(json.dumps(payload, indent=2) + "\n",
                           encoding="utf-8")
    harness = outdir / f"harness-{_HERE.name}.py"
    harness.write_text(_HARNESS, encoding="utf-8")
    started = time.time()
    try:
        proc = subprocess.run(
            [sys.executable, str(harness), str(candidate.resolve()),
             str(probes_file)],
            capture_output=True, text=True, timeout=180, cwd=str(_HERE))
    except subprocess.TimeoutExpired:
        return 0, len(probes), time.time() - started, [{
            "code": "PAIR_MISMATCH",
            "detail": f"candidate invocation exceeded the 180s wall cap "
                      f"(0/{len(probes)} probes graded)",
        }]
    ttc = time.time() - started
    matched = _grade(probes, expected, _parse_rows(proc.stdout))
    return matched, len(probes), ttc, []


def _replay_face(gt: dict, candidate: Path, outdir: Path) -> dict:
    """The replay-roundtrip face: published pairs + checker-minted probes
    (expected outputs minted by the held-out host oracle). Returns the
    faces.replay row; raises Skip when the oracle is unavailable."""
    probes = [{"i": p["i"], "input": p["input"]}
              for p in gt["published_pairs"]]
    inputs: dict[int, bytes] = {}
    minted = gt.get("minted_probe_count", 0)
    if minted:
        base = 1000  # minted ids never collide with published ids
        for off, blob in enumerate(minted_inputs(gt["seed"], minted)):
            inputs[base + off] = blob
            probes.append({"i": base + off, "input": list(blob)})
    expected: dict[int, dict] = {p["i"]: {"verify": p["verify"],
                                          "probe": p["probe"]}
                                 for p in gt["published_pairs"]}
    expected.update(host_expected(_HERE / "target" / "crackme_host",
                                  inputs))
    matched, count, ttc, notes = _candidate_replay(
        candidate, probes, expected, outdir)
    return {"matched": matched, "count": count,
            "ttc_seconds": round(ttc, 3),
            "toolchain": "python3", "notes": notes}


# -------------------------------------------------------------------- run
def run(candidate: Path, out: Path | None) -> int:
    task, gt = load_unit()
    validate_candidate(candidate)
    oracles = task["checker"].get("oracles", [])
    thresholds = task["checker"].get("thresholds", {})

    outdir = Path(out) if out else ds.EVAL_ROOT.parent / "runs" / "eval" / _HERE.name
    outdir.mkdir(parents=True, exist_ok=True)
    ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    failures: list[dict] = []
    faces: dict = {}
    hits, pair_matched, pair_count, ttc, dispatch = 0, 0, 0, 0.0, 0

    # ---- static face (constant-hit) — shared protocol helper
    if "constant-hit" in oracles:
        hits, missing = eval_checker.static_face(candidate, gt)
        faces["static"] = {"hits": hits,
                           "required": thresholds.get("min_constant_hits", 0),
                           "missing": missing}

    # ---- replay face (replay-roundtrip)
    replay_armed = any(o in oracles for o in ("pair-match",
                                              "replay-roundtrip"))
    if replay_armed:
        try:
            replay_row = _replay_face(gt, candidate, outdir)
        except Skip as exc:
            failures.append({"code": "TOOLCHAIN_MISSING", "detail": str(exc)})
            faces["replay"] = {"toolchain": "crackme_host", "skipped": True}
        else:
            pair_matched = replay_row["matched"]
            pair_count = replay_row["count"]
            ttc = replay_row["ttc_seconds"]
            dispatch = 1
            failures.extend(replay_row.pop("notes"))
            faces["replay"] = replay_row

    # ---- arithmetic verdict (shared helper)
    if any(f["code"] == "TOOLCHAIN_MISSING" for f in failures):
        verdict, rc = "SKIP", RC_SKIP
    else:
        ok, arith_failures = ds.arithmetic_verdict(
            hits=hits,
            min_constant_hits=thresholds.get("min_constant_hits", 0)
            if "constant-hit" in oracles else 0,
            pairs_matched=pair_matched,
            pair_count=pair_count if replay_armed else 0,
            min_pair_ratio=thresholds.get("min_pair_ratio", 1.0)
            if replay_armed else 1.0)
        failures.extend(arith_failures)
        verdict = "PASS" if ok else "FAIL"
        rc = RC_PASS if ok else RC_FAIL

    metrics = {
        "ttc_seconds": round(ttc, 3),
        "dispatch_count": dispatch,
        "pass_at_k_contribution": 1 if verdict == "PASS" else 0,
        "converged": 1 if verdict == "PASS" and not failures else 0,
    }

    cand_digest = hashlib.sha256(candidate.read_bytes()).hexdigest()
    evidence = {
        "schema": ds.EVIDENCE_SCHEMA,
        "task_id": _HERE.name,
        "eval_version": task["eval_version"],
        "family": task["family"],
        "tier": task["tier"],
        "ts": ts,
        "candidate": str(candidate),
        "candidate_sha256": cand_digest,
        "faces": faces,
        "metrics": metrics,
        "verdict": verdict,
        "verdict_class": None,
        "failures": failures,
    }
    ev_path = outdir / (
        f"evidence-{_HERE.name}-{time.strftime('%Y%m%dT%H%M%SZ')}-"
        f"{__import__('os').getpid() % 100000}.json")
    ev_path.write_text(json.dumps(evidence, indent=2) + "\n",
                       encoding="utf-8")

    for name, value in metrics.items():
        print(ds.metric_line(name, value))
    for f in failures:
        print(f"FAILURE code={f['code']} detail={f['detail']}")
    print(f"EVIDENCE {ev_path}")
    print(f"VERDICT {verdict}")
    return rc


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="checker.py",
        description="Mechanical checker for rust-so-crack-v1 (host-oracle "
                    "replay-roundtrip; METRIC emission, arithmetic verdict, "
                    "evidence archive).")
    ap.add_argument("--candidate", default=None,
                    help="candidate artifact (a .py module exposing "
                         "verify/probe); default: the unit's reference.py "
                         "(self-check)")
    ap.add_argument("--out", default=None,
                    help="evidence out-dir (default: runs/eval/<task_id>/)")
    args = ap.parse_args(argv)
    candidate = (Path(args.candidate) if args.candidate
                 else _HERE / "reference.py")
    try:
        return run(candidate, Path(args.out) if args.out else None)
    except Refusal as exc:
        print(f"FAILURE code={exc.code} detail={exc.detail}")
        print("VERDICT REFUSED")
        return RC_REFUSED


if __name__ == "__main__":
    raise SystemExit(main())
