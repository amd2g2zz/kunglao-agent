#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""test_inventory.py — bloat-classification inventory over tests/.

Evidence BEFORE deletion (Face 1): classifies every test function in
tests/ into zero or more bloat classes and emits per-class counts.

Classes:
  mock_shape_only      every assert in the test body is a mock-call-shape
                       assertion (assert_called*_with / called / call_count
                       family) and no observable value is asserted.
  generated_golden     test references a CI-REGENERATED artifact
                       (deploy-manifest.yaml outputs / .claude/ deployed
                       tree / ext index) as a golden to pin — the copy is
                       regenerated by tooling, so the pin duplicates CI.
  dead_code_pin        every scripts//hooks/ production symbol the test
                       exercises has ZERO non-test references in the repo
                       (static approximation; deletion requires a GitNexus
                       cross-check per the method contract).
  param_redundant      parametrized >= MIN_REDUNDANT_CASES cases where the
                       body has no branching and at most one assert — N
                       cases asserting the same branch.

Output: JSON (machine) + Markdown (human) into devkit/reports/ by default.
DESCRIBE-ONLY: this tool never modifies anything; it reads and reports.

Usage:
  uv run python scripts/test_inventory.py [--tests-dir tests] \
      [--json PATH] [--md PATH]
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# canonical warn: ONE implementation (process-wide dedupe + ledger face)
from kunglao_log import warn

MOCK_ASSERT_RE = re.compile(
    r"assert_(called|not_called|any_call|called_once|called_once_with|"
    r"called_with|not_called|not_awaited|awaited|awaited_once|"
    r"awaited_once_with|awaited_with|has_calls|not_has_calls)"
)
# Attribute accesses that read mock shape without asserting it (call_count).
MOCK_SHAPE_ATTRS = {"called", "call_count", "await_count", "mock_calls",
                    "call_args", "call_args_list"}
# String-literal markers of CI-regenerated artifacts (Face 1 class 2).
GENERATED_MARKERS = (
    "deploy-manifest.yaml",
    "_INDEX.ext.yaml",
    ".claude/scripts/",
    ".claude/hooks/",
    ".claude/agents/",
)
MIN_REDUNDANT_CASES = 6

# Where non-test production references may live (dead_code_pin evidence).
PROD_REF_DIRS = ("scripts", "hooks", "tools", "devkit", "agents", "skills",
                 ".github", "templates")
PROD_REF_FILES = ("README.md", "README.zh-CN.md", "AGENTS.md", "CLAUDE.md",
                  "SKILL.md", "deploy-manifest.yaml", "release-manifest.yaml",
                  "conftest.py", "pytest.ini")


@dataclass(frozen=True)
class TestInfo:
    file: str
    name: str
    line: int
    classes: tuple[str, ...]
    detail: str = ""


@dataclass
class SuiteStats:
    files: int = 0
    functions: int = 0
    by_class: dict[str, list[TestInfo]] = field(default_factory=dict)

    def add(self, cls: str, info: TestInfo) -> None:
        self.by_class.setdefault(cls, []).append(info)


def _iter_test_files(tests_dir: Path) -> list[Path]:
    return sorted(p for p in tests_dir.rglob("*.py")
                  if p.name.startswith("test_") or p.name == "conftest.py")


def _parametrize_cases(decorator_list: list[ast.expr]) -> int:
    """Product of stacked @pytest.mark.parametrize case counts (best effort)."""
    total = 1
    found = False
    for dec in decorator_list:
        node = dec
        if isinstance(node, ast.Call):
            node = node.func
        name = ""
        if isinstance(node, ast.Attribute):
            name = node.attr
        elif isinstance(node, ast.Name):
            name = node.id
        if name != "parametrize":
            continue
        if isinstance(dec, ast.Call) and dec.args:
            arg = dec.args[-1]
            if isinstance(arg, (ast.List, ast.Tuple)):
                total *= len(arg.elts)
                found = True
    return total if found else 0


def _assert_facts(fn: ast.AST) -> tuple[int, int]:
    """(total_asserts, mock_shape_asserts) inside a test function body."""
    total = mock = 0

    def is_mock_expr(node: ast.expr) -> bool:
        # STRICT: only unittest.mock-library shape assertions count
        # (assert_called*_with / has_calls family). Fakes/spies that
        # observe real behavior assert observable values and are NOT
        # bloat ("tests that only assert mock-call shapes").
        for n in ast.walk(node):
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute):
                if MOCK_ASSERT_RE.search(n.func.attr):
                    return True
        return False

    for node in ast.walk(fn):
        if not isinstance(node, ast.Assert):
            continue
        total += 1
        if is_mock_expr(node.test):
            mock += 1
    return total, mock


def _has_branching(fn: ast.AST) -> bool:
    return any(isinstance(n, (ast.If, ast.For, ast.While, ast.Try,
                              ast.Match))
               for n in ast.walk(fn))


def _string_literals(fn: ast.AST) -> list[str]:
    out: list[str] = []
    for node in ast.walk(fn):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            out.append(node.value)
    return out


def _module_defs(stem: str) -> set[str]:
    """Top-level def/class names of a scripts//hooks/ module (AST, cached)."""
    cached = _module_defs._cache.get(stem)
    if cached is not None:
        return cached
    names: set[str] = set()
    for base in ("scripts", "hooks"):
        p = ROOT / base / f"{stem}.py"
        if p.is_file():
            try:
                text = p.read_text(encoding="utf-8")
                tree = ast.parse(text)
            except (SyntaxError, OSError):
                continue
            for node in tree.body:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef,
                                     ast.ClassDef)):
                    names.add(node.name)
            # self-reference counts: a name whose ONLY occurrence in its own
            # module is the `def`/`class` line has no in-module caller.
            _module_selfref_cache[stem] = {
                n: len(re.findall(rf"\b{re.escape(n)}\b", text))
                for n in names
            }
            break
    _module_defs._cache[stem] = names  # type: ignore[attr-defined]
    return names


_module_defs._cache: dict[str, set[str]] = {}  # type: ignore[attr-defined]
_module_selfref_cache: dict[str, dict[str, int]] = {}


def _prod_ref_words() -> dict[Path, set[str]]:
    """Per-file word sets outside tests/ (dead-code evidence, O(1) checks).

    The DEFINING module is excluded per-symbol at query time: a definition
    alone is not a live reference (class-3 semantics).
    """
    if _prod_ref_words._cache is not None:
        return _prod_ref_words._cache
    out: dict[Path, set[str]] = {}
    for d in PROD_REF_DIRS:
        base = ROOT / d
        if not base.is_dir():
            continue
        for p in base.rglob("*"):
            if p.is_file() and (p.suffix in (".py", ".yaml", ".yml", ".md",
                                             ".json", ".toml", ".sh")
                                or p.name in ("Dockerfile",)):
                try:
                    text = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
                out[p] = set(re.findall(r"\w+", text))
    for name in PROD_REF_FILES:
        p = ROOT / name
        if p.is_file():
            out[p] = set(re.findall(
                r"\w+", p.read_text(encoding="utf-8", errors="replace")))
    _prod_ref_words._cache = out  # type: ignore[attr-defined]
    return _prod_ref_words._cache  # type: ignore[attr-defined]


_prod_ref_words._cache = None  # type: ignore[attr-defined]


def _imported_script_modules(tree: ast.Module) -> set[str]:
    """Level-0 imports that resolve to scripts/ or hooks/ module stems."""
    stems: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                stem = alias.name.split(".")[0]
                if (ROOT / "scripts" / f"{stem}.py").is_file() or (
                        ROOT / "hooks" / f"{stem}.py").is_file():
                    stems.add(stem)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            stem = node.module.split(".")[0]
            if (ROOT / "scripts" / f"{stem}.py").is_file() or (
                    ROOT / "hooks" / f"{stem}.py").is_file():
                stems.add(stem)
    return stems


def _used_names(fn: ast.AST, local_defs: set[str]) -> set[str]:
    used: set[str] = set()
    for node in ast.walk(fn):
        if isinstance(node, ast.Name) and node.id in local_defs:
            used.add(node.id)
        elif isinstance(node, ast.Attribute) and node.attr in local_defs:
            used.add(node.attr)
    return used


def _dead_subjects(used: set[str], index: dict[Path, set[str]],
                   imported_stems: set[str]) -> list[str]:
    """Subjects with no live caller: zero references outside the defining
    module AND at most one in-module occurrence (the def line itself).
    A function dispatched by its own wired module's main() is ALIVE.
    """
    # Only the symbol's OWN defining module may be excluded from the
    # reference scan. Excluding every imported stem hid live cross-module
    # callers (hooks/session_start.py consuming compact_continuity.
    # consume_stashed_note) — the false-positive class found and removed
    stem_paths = {stem: [ROOT / base / f"{stem}.py"
                         for base in ("scripts", "hooks")
                         if (ROOT / base / f"{stem}.py").is_file()]
                  for stem in imported_stems}
    dead = []
    for name in used:
        defining = {p for stem in imported_stems
                    if name in _module_defs(stem)
                    for p in stem_paths[stem]}
        # self-poisoning guard: this tool's own committed reports must not
        # count as references (they repeat prior-run subject names).
        if any(name in words for f, words in index.items()
               if f not in defining
               and not f.name.startswith("test-inventory-")):
            continue
        self_refs = -1
        for stem in imported_stems:
            if name in _module_defs(stem):
                self_refs = max(
                    self_refs,
                    _module_selfref_cache.get(stem, {}).get(name, 2))
        if self_refs == -1:
            continue  # not a module-level def we can reason about → keep
        if self_refs <= 1:
            dead.append(name)  # def line only, no in-module caller
    return dead


def _unwired_modules(index: dict[Path, set[str]],
                     imported_stems: set[str]) -> list[str]:
    """Modules with NO production reference outside their own file.

    Matches the scripts/README.md 'unwired-live' ledger semantics: a module
    reachable only from tests/ (or from nothing) is unwired. Counts as
    wiring: real consumption edges from hooks/, scripts/, tools/ code,
    devkit/, agents/, skills/, CI, templates/, runtime-loaded teaching
    (AGENTS/CLAUDE/SKILL) and the internal registry tools/_INDEX.yaml.
    NOT wiring: the generated deployment closure (deploy-manifest.yaml,
    release-manifest.yaml — being shipped is not being reached), the
    DESCRIBE-ONLY ext index (_INDEX.ext.yaml), and human docs (README*).
    """
    not_wiring = {
        "deploy-manifest.yaml", "release-manifest.yaml",
        "_INDEX.ext.yaml", "README.md", "README.zh-CN.md",
    }
    unwired = []
    for stem in sorted(imported_stems):
        defining = {ROOT / base / f"{stem}.py" for base in ("scripts", "hooks")}
        if not any(stem in words
                   for f, words in index.items()
                   if f not in defining and f.name not in not_wiring
                   and not f.name.startswith("test-inventory-")):
            unwired.append(stem)
    return unwired


def _dead_pin_facts(node: ast.AST, script_stems: set[str],
                    local_defs: set[str],
                    ref_index: dict) -> tuple[list[str], list[str]]:
    """Dead-code-pin facts for one test: which imported subject modules
    are unwired / dead from here."""
    classes: list[str] = []
    details: list[str] = []
    used = _used_names(node, local_defs)
    unwired = _unwired_modules(ref_index, script_stems)
    dead = _dead_subjects(used, ref_index, script_stems)
    if script_stems and unwired == sorted(script_stems):
        # whole-module pin: every imported subject module is
        # unwired (reachable only from tests/) — the
        # dead-code-pin class, unwired-live semantics.
        classes.append("dead_code_pin")
        details.append(f"unwired modules: {','.join(unwired)}")
    elif used and len(dead) == len(used):
        classes.append("dead_code_pin")
        details.append(f"dead subjects: {','.join(dead)}")
    return classes, details


def _classify_test_facts(node: ast.AST, script_stems: set[str],
                         local_defs: set[str],
                         ref_index: dict) -> tuple[list[str], list[str]]:
    """The inventory taxonomy for one test function:
    mock_shape_only / generated_golden / dead_code_pin / param_redundant."""
    classes: list[str] = []
    details: list[str] = []

    total_a, mock_a = _assert_facts(node)
    if total_a > 0 and mock_a == total_a:
        classes.append("mock_shape_only")
        details.append(f"{mock_a}/{total_a} asserts are mock-shape")

    literals = " ".join(_string_literals(node))
    gen_hits = [m for m in GENERATED_MARKERS if m in literals]
    if gen_hits:
        classes.append("generated_golden")
        details.append(f"pins regenerated artifact: {gen_hits[0]}")

    if local_defs:
        pin_c, pin_d = _dead_pin_facts(node, script_stems, local_defs,
                                       ref_index)
        classes += pin_c
        details += pin_d

    cases = _parametrize_cases(node.decorator_list)
    if cases >= MIN_REDUNDANT_CASES and not _has_branching(node):
        n_asserts = sum(1 for n in ast.walk(node)
                        if isinstance(n, ast.Assert))
        if n_asserts <= 1:
            classes.append("param_redundant")
            details.append(f"{cases} cases, branch-free, "
                           f"{n_asserts} assert(s)")
    return classes, details


def classify_file(path: Path, rel: str, stats: SuiteStats) -> None:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError as exc:
        warn("inventory_unparsable", f"unparsable {rel}: {exc}")
        return
    stats.files += 1
    script_stems = _imported_script_modules(tree)
    local_defs: set[str] = set()
    for stem in script_stems:
        local_defs |= _module_defs(stem)
    ref_index = _prod_ref_words() if local_defs else {}

    class_stack: list[str] = []

    def visit_body(body: list[ast.stmt], cls: str) -> None:
        for node in body:
            if isinstance(node, ast.ClassDef):
                class_stack.append(node.name)
                visit_body(node.body, node.name)
                class_stack.pop()
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if not node.name.startswith("test_"):
                    continue
                stats.functions += 1
                classes, details = _classify_test_facts(
                    node, script_stems, local_defs, ref_index)
                if classes:
                    qual = (f"{cls}." if cls else "") + node.name
                    info = TestInfo(rel, qual, node.lineno,
                                    tuple(classes), "; ".join(details))
                    for c in classes:
                        stats.add(c, info)

    visit_body(tree.body, "")


def build_inventory(tests_dir: Path) -> SuiteStats:
    stats = SuiteStats()
    for p in _iter_test_files(tests_dir):
        classify_file(p, p.relative_to(ROOT).as_posix(), stats)
    return stats


def to_json(stats: SuiteStats) -> dict:
    return {
        "schema": "test-inventory/1",
        "issue": 807,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "totals": {"files": stats.files, "test_functions": stats.functions},
        "classes": {
            cls: {
                "count": len(items),
                "items": [
                    {"file": i.file, "test": i.name, "line": i.line,
                     "detail": i.detail}
                    for i in items
                ],
            }
            for cls, items in sorted(stats.by_class.items())
        },
    }


def to_md(stats: SuiteStats) -> str:
    lines = [
        "# Test inventory — bloat classification",
        "",
        f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')} "
        f"by `scripts/test_inventory.py` (DESCRIBE-ONLY).",
        "",
        "| metric | value |",
        "|---|---|",
        f"| test files | {stats.files} |",
        f"| test functions | {stats.functions} |",
    ]
    for cls in ("mock_shape_only", "generated_golden", "dead_code_pin",
                "param_redundant"):
        items = stats.by_class.get(cls, [])
        lines.append(f"| {cls} candidates | {len(items)} |")
    lines += ["", "Candidates are HEURISTIC — every deletion requires manual "
              "verification + GitNexus dead-code cross-check (method "
              "contract).", ""]
    for cls in ("mock_shape_only", "generated_golden", "dead_code_pin",
                "param_redundant"):
        items = stats.by_class.get(cls, [])
        if not items:
            continue
        lines += [f"## {cls} ({len(items)})", "",
                  "| file | test | line | detail |", "|---|---|---|---|"]
        for i in items:
            lines.append(f"| {i.file} | `{i.name}` | {i.line} | {i.detail} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tests-dir", default="tests")
    ap.add_argument("--json", default=str(ROOT / "devkit/reports/"
                                          "test-inventory-807.json"))
    ap.add_argument("--md", default=str(ROOT / "devkit/reports/"
                                        "test-inventory-807.md"))
    args = ap.parse_args(argv)
    stats = build_inventory(ROOT / args.tests_dir)
    payload = to_json(stats)
    out_json = Path(args.json)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(payload, indent=2) + "\n",
                        encoding="utf-8")
    out_md = Path(args.md)
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(to_md(stats) + "\n", encoding="utf-8")
    print(f"files={stats.files} functions={stats.functions}")
    for cls, items in sorted(stats.by_class.items()):
        print(f"  {cls}: {len(items)}")
    print(f"wrote {out_json}")
    print(f"wrote {out_md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
