class Refusal(Exception):
    def __init__(self, code: str, detail: str):
        super().__init__(detail)
        self.code = code
        self.detail = detail


def _verdict_face(checker: dict, candidate: Path, gt: dict,
                  thresholds: dict) -> tuple[str, bool, list]:
    """Dispatch the verdict-class faces (misdirection tier); malformed
    verdict documents are candidate refusals, never crashes."""
    try:
        if checker["kind"] == "misdirection-verdict":
            return md.misdirection_verdict_face(candidate, gt, thresholds)
        return md.rotation_verdict_face(candidate, gt, thresholds)
    except ValueError as exc:
        raise Refusal("BAD_CANDIDATE",
                      f"verdict artifact invalid: {exc}") from None


# --------------------------------------------------------------- unit loading
def load_unit(task_ref: str, tier: str | None = None) -> tuple[Path, dict, dict]:
    try:
        tdir = ds.resolve_task_dir(task_ref, tier=tier)
    except FileNotFoundError as exc:
        raise Refusal("BAD_TASK", str(exc)) from exc
    task = ds.load_task(tdir)
    ok, errors = ds.validate_task(task)
    if not ok:
        raise Refusal("BAD_TASK", f"{tdir.name}: {'; '.join(errors)}")
    gt_path = tdir / task["ground_truth"]["file"]
    if not gt_path.is_file():
        raise Refusal("BAD_TASK", f"ground truth missing: {gt_path}")
    gt = json.loads(gt_path.read_text(encoding="utf-8"))
    if gt.get("schema") != tg.SCHEMA_GROUND_TRUTH:
        raise Refusal("BAD_TASK", f"ground truth schema {gt.get('schema')!r}")
    return tdir, task, gt


def _family_meta(family: str) -> dict:
    """The family registry row: #299 smoke families live in eval_targets,
    the #332 native families in eval_native_targets, the misdirection
    families in eval_misdirection."""
    if family in md.FAMILIES:
        return md.FAMILIES[family]
    if family in ntg.FAMILIES:
        return ntg.FAMILIES[family]
    return tg.FAMILIES[family]


def _validate_candidate(path: Path, family: str) -> None:
    if not path.is_file():
        raise Refusal("BAD_CANDIDATE", f"candidate not found: {path}")
    try:
        want = contract.candidate_suffix(family)
    except KeyError:
        raise Refusal("BAD_TASK", f"unknown family: {family!r}") from None
    if path.suffix != want:
        raise Refusal("BAD_CANDIDATE",
                      f"family {family} needs a {want} candidate, got {path.suffix}")


# --------------------------------------------------------------- static face
def static_face(candidate: Path, gt: dict) -> tuple[int, list[str]]:
    """constant-hit: count ground-truth constants present in the candidate
    source (zero-padded or unpadded hex, case-insensitive, or decimal;
    hex-string constants like key_hex are matched as the literal string)."""
    text = candidate.read_text(encoding="utf-8", errors="replace").lower()
    hits, missing = 0, []
    for name, value in gt.get("constants", {}).items():
        if isinstance(value, str):
            forms = (value.lower(),)
        else:
            forms = (f"0x{value:08x}", f"0x{value:016x}", f"0x{value:x}",
                     str(value))
        if any(form in text for form in forms):
            hits += 1
        else:
            missing.append(name)
    return hits, missing


# --------------------------------------------------------------- replay face
class Skip(Exception):
    pass


def _toolchain(toolchain: str) -> str:
    if toolchain == "python3":
        return sys.executable
    path = shutil.which(toolchain)
    if path is None:
        raise Skip(f"{toolchain} toolchain not available on this machine")
    return path


def _probe_set(family: str, gt: dict) -> list[dict]:
    """Published pairs + checker-minted probes (anti-digest-table face).
    Request families carry object probes on the ``request`` key; byte
    families carry byte lists on ``input``."""
    if family in md.FAMILIES:
        return md.probes_for(gt)
    probes = []
    for p in gt["published_pairs"]:
        if family in REQUEST_FAMILIES:
            probes.append({"i": p["i"], "request": p["request"]})
        else:
            probes.append({"i": p["i"], "input": p["input"]})
    minted = gt.get("minted_probe_count", 0)
    if minted:
        if family in ntg.FAMILIES:
            probes += ntg.minted_probes(family, gt["seed"], minted)
        else:
            probes += tg.minted_probes(family, gt["seed"], minted)
    return probes


def _expected(family: str, gt: dict, probes: list[dict]) -> dict[int, object]:
    if family in md.FAMILIES:
        return md.expected_for(gt, probes)
    if family in ntg.FAMILIES:
        cfg = {"seed": gt["seed"]}
        return {p["i"]: ntg.model_output(family, cfg, p["i"], p["input"])
                for p in probes}
    cfg = tg.model_cfg(gt)
    out = {}
    for p in probes:
        x = p.get("request", p.get("input"))
        out[p["i"]] = tg.model_output(family, cfg, p["i"], x)
    return out


def _write_probes(family: str, tdir: Path, outdir: Path,
                  probes: list[dict]) -> tuple[Path, str]:
    """Persist the probe file (request families embed the candidate seam
    name) and return (probes_file, stdin_text for the go face)."""
    probes_file = outdir / f"probes-{tdir.name}.json"
    if family in REQUEST_FAMILIES:
        payload = {"schema": "kunglao-eval-probes/1",
                   "task_id": tdir.name,
                   "call": tg.FAMILIES[family]["anchor_fn"],
                   "probes": probes}
        probes_file.write_text(
            json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    else:
        payload = {"schema": "kunglao-eval-probes/1",
                   "task_id": tdir.name, "probes": probes}
        probes_file.write_text(
            json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    stdin_text = ""
    if family in GO_STDIN_FAMILIES:
        stdin_text = "".join(
            json.dumps({"i": p["i"], "in": p["input"][0]}) + "\n"
            for p in probes)
        probes_file = outdir / f"probes-{tdir.name}.stdin"
        probes_file.write_text(stdin_text, encoding="utf-8")
    return probes_file, stdin_text


def _invocation(family: str, tdir: Path, exe: str, candidate: Path,
                probes: list[dict],
                outdir: Path) -> tuple[list, str | None, Path]:
    """Per-family candidate invocation: command, stdin text, probes file
    (the merged #332 surface: go stdin face, request + sign-bytes js
    harnesses, native/py entry harnesses)."""
    probes_file, go_stdin = _write_probes(family, tdir, outdir, probes)
    if family in GO_STDIN_FAMILIES:
        # input-agnostic seam: the candidate reads {"i","in"} lines on
        # stdin; the checker drives published + freshly minted inputs
        # through it (inputs only on the wire; expected outputs stay
        # checker-side, recomputed from the seed model — stored nowhere)
        return [exe, "run", str(candidate)], go_stdin, probes_file
    if family in REQUEST_FAMILIES:
        harness = outdir / f"harness-{tdir.name}.js"
        harness.write_text(_JS_REQUEST_HARNESS, encoding="utf-8")
    elif family in SIGN_BYTES_FAMILIES:
        harness = outdir / f"harness-{tdir.name}.js"
        harness.write_text(_JS_HARNESS, encoding="utf-8")
    else:
        harness = outdir / f"harness-{tdir.name}.py"
        entry = (ntg.CANDIDATE_ENTRIES[family]
                 if family in ntg.FAMILIES else "derive")
        harness.write_text(_PY_HARNESS.replace("{entry}", entry),
                           encoding="utf-8")
    return [exe, str(harness), str(candidate), str(probes_file)], \
        None, probes_file




def replay_face(family: str, tdir: Path, gt: dict, candidate: Path,
                outdir: Path, toolchain: str) -> tuple[int, int, float, list[dict]]:
    """Run the candidate over the probe set; return (matched, count, ttc,
    extra failure signals)."""
    exe = _toolchain(toolchain)
    # absolute paths: the subprocess runs with cwd=<task dir>, so relative
    # candidate/out paths from the caller would not resolve
    outdir = Path(outdir).resolve()
    candidate = Path(candidate).resolve()
    probes = _probe_set(family, gt)
    expected = _expected(family, gt, probes)
    cmd, stdin_text, probes_file = _invocation(family, tdir, exe, candidate,
                                               probes, outdir)
    notes: list[dict] = []
    started = time.time()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=180, cwd=str(tdir), input=stdin_text)
    except subprocess.TimeoutExpired:
        notes.append({
            "code": "PAIR_MISMATCH",
            "detail": f"candidate invocation exceeded the 180s wall cap "
                      f"(0/{len(probes)} probes graded)",
        })
        return 0, len(probes), time.time() - started, notes
    ttc = time.time() - started

    got: dict[int, tuple] = {}
    for line in proc.stdout.splitlines():
        if not LINE_JSON.match(line):
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        i = row.get("i")
        if isinstance(i, int):
            got[i] = (row.get("in"), row.get("out"))

    matched = 0
    for p in probes:
        pair = got.get(p["i"])
        if pair is None:
            continue
        inputs = p.get("input")
        want_in = tuple(inputs)[0] if inputs and len(inputs) == 1 else None
        if want_in is not None and pair[0] is not None and pair[0] != want_in:
            continue  # candidate evaluated the wrong input
        if pair[1] == expected[p["i"]]:
            matched += 1
    return matched, len(probes), ttc, notes


# ------------------------------------------------------- license replay face
class LicenseMockServer:
    """Loopback-only mock license server (the net-verify-license oracle).

    NO-EGRESS GUARANTEE, enforced here: the socket binds ("127.0.0.1", 0)
    — loopback only, ephemeral port — and the base URL reaches the
    candidate via the generated harness argv, never a host literal. The
    server recomputes the expected response = HMAC(KDF(challenge, secret),
    canonical_payload) from the SEED model checker-side (server-side
    validation on published + checker-minted challenges; a canned
    response or a forged session validates nothing)."""

    def __init__(self, cfg: dict, probes: list[dict]):
        self.cfg = cfg
        self.probes = {p["i"]: p for p in probes}
        self.issued: dict[str, int] = {}   # session token -> probe i
        self.results: dict[int, bool] = {}  # probe i -> server-side verdict
        self._httpd = None
        self._thread = None

    def start(self) -> int:
        from http.server import BaseHTTPRequestHandler, HTTPServer
        outer = self

        class _Handler(BaseHTTPRequestHandler):
            def do_POST(self):
                try:
                    n = int(self.headers.get("content-length", 0) or 0)
                    body = json.loads(self.rfile.read(n) or b"{}")
                except (ValueError, json.JSONDecodeError):
                    body = {}
                if self.path == "/challenge":
                    probe = outer.probes.get(body.get("i"))
                    if probe is None:
                        self._send(404, {"error": "unknown probe"})
                        return
                    i = probe["i"]
                    token = hashlib.sha256(
                        f"{probe['challenge']}|{probe['client_nonce']}|"
                        f"{i}".encode("utf-8")).hexdigest()[:16]
                    outer.issued[token] = i
                    self._send(200, {"session": token,
                                     "challenge": probe["challenge"]})
                elif self.path == "/verify":
                    token = str(body.get("session", ""))
                    i = outer.issued.get(token)
                    if i is None:
                        self._send(200, {"valid": False, "i": None})
                        return
                    probe = outer.probes[i]
                    expected = tg.license_response(
                        outer.cfg, probe["challenge"],
                        probe["client_nonce"], outer.cfg["device"], i)
                    ok = hmac.compare_digest(
                        str(body.get("response", "")), expected)
                    outer.results[i] = bool(ok)
                    self._send(200, {"valid": bool(ok), "i": i})
                else:
                    self._send(404, {"error": "not found"})

            def _send(self, code: int, obj: dict) -> None:
                payload = json.dumps(obj).encode("utf-8")
                self.send_response(code)
                self.send_header("content-type", "application/json")
                self.send_header("content-length", str(len(payload)))
                self.end_headers()
                self.wfile.write(payload)

            def log_message(self, *args):
                return  # loopback-only face: keep the run log clean

        self._httpd = HTTPServer(("127.0.0.1", 0), _Handler)
        import threading
        self._thread = threading.Thread(target=self._httpd.serve_forever,
                                        daemon=True)
        self._thread.start()
        return self._httpd.server_address[1]

    def stop(self) -> None:
        if self._httpd is not None:
            self._httpd.shutdown()
            self._httpd.server_close()
            self._httpd = None


def _license_probe_set(gt: dict) -> list[dict]:
    """Published challenges (fixed seed face) + checker-minted challenges
    (fresh seed lanes — the anti-replay face for the protocol)."""
    probes = [{"i": p["i"], "challenge": p["challenge"],
               "client_nonce": p["client_nonce"]}
              for p in gt["published_pairs"]]
    minted = gt.get("minted_probe_count", 0)
    if minted:
        probes += tg.minted_probes("net-verify-license", gt["seed"], minted)
    return probes


def license_face(tdir: Path, gt: dict, candidate: Path, outdir: Path,
                 toolchain: str) -> tuple[int, int, float, list[dict]]:
    """Challenge/response roundtrip through the loopback mock server:
    matched = sessions the SERVER marked valid AND whose session token
    the candidate actually echoed."""
    exe = _toolchain(toolchain)
    outdir = Path(outdir).resolve()
    candidate = Path(candidate).resolve()
    core = tg.model_cfg(gt)
    probes = _license_probe_set(gt)

    server = LicenseMockServer(core, probes)
    port = server.start()
    started = time.time()
    notes: list[dict] = []
    try:
        config = {
            # loopback base URL built from the ephemeral bind — never a
            # host literal in any artifact or harness
            "serverUrl": f"http://127.0.0.1:{port}",
            "probes": [{"i": p["i"], "client_nonce": p["client_nonce"],
                        "device": core["device"]} for p in probes],
        }
        cfg_file = outdir / f"license-config-{tdir.name}.json"
        cfg_file.write_text(json.dumps(config, indent=2) + "\n",
                            encoding="utf-8")
        harness = outdir / f"harness-{tdir.name}.js"
        harness.write_text(_JS_LICENSE_HARNESS, encoding="utf-8")
        try:
            proc = subprocess.run(
                [exe, str(harness), str(candidate), str(cfg_file)],
                capture_output=True, text=True, timeout=180, cwd=str(tdir))
        except subprocess.TimeoutExpired:
            notes.append({
                "code": "PAIR_MISMATCH",
                "detail": f"license handshake exceeded the 180s wall cap "
                          f"(0/{len(probes)} sessions graded)",
            })
            return 0, len(probes), time.time() - started, notes
        ttc = time.time() - started

        rows: dict[int, str] = {}
        for line in proc.stdout.splitlines():
            if not LINE_JSON.match(line):
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(row.get("i"), int):
                rows[row["i"]] = row.get("session")
        matched = 0
        for p in probes:
            i = p["i"]
            token = rows.get(i)
            if token is not None and server.issued.get(token) == i \
                    and server.results.get(i) is True:
                matched += 1
        return matched, len(probes), ttc, notes
    finally:
        server.stop()


# -------------------------------------------------------------------- run
def run(task_ref: str, candidate: Path, out: Path | None = None,
        tier: str = "smoke") -> tuple[int, dict]:
    """Check one task; returns (exit_code, evidence_dict). Emits the
    METRIC/FAILURE/EVIDENCE/VERDICT stream on stdout."""
    tdir, task, gt = load_unit(task_ref, tier=tier)
    family = task["family"]
    checker = task["checker"]
    oracles = checker.get("oracles", [])
    thresholds = checker.get("thresholds", {})
    _validate_candidate(candidate, family)

    outdir = Path(out) if out else ds.EVAL_ROOT.parent / "runs" / "eval" / tdir.name
    outdir.mkdir(parents=True, exist_ok=True)
    ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    failures: list[dict] = []
    faces: dict = {}
    hits, pair_matched, pair_count, ttc, dispatch = 0, 0, 0, 0.0, 0

    # ---- verdict-class faces (misdirection tier) ----
    # the graded artifact is a schema-checked verdict document; the face
    # discriminates the trap's verdict classes mechanically
    verdict_kind = checker["kind"] in md.VERDICT_KINDS
    verdict_class, ok_face = None, False
    if verdict_kind:
        verdict_class, ok_face, face_failures = _verdict_face(
            checker, candidate, gt, thresholds)
        faces["verdict"] = {"class": verdict_class}
        failures.extend(face_failures)

    # ---- static face (constant-hit) ----
    if "constant-hit" in oracles:
        hits, missing = static_face(candidate, gt)
        faces["static"] = {"hits": hits,
                           "required": thresholds.get("min_constant_hits", 0),
                           "missing": missing}
        # the CONSTANT_MISS failure signal is owned by arithmetic_verdict

    # ---- replay face ----
    replay_armed = any(o in oracles for o in ("pair-match", "replay-roundtrip"))
    if replay_armed:
        toolchain = _family_meta(family)["toolchain"]
        try:
            if family == "net-verify-license":
                pair_matched, pair_count, ttc, notes = license_face(
                    tdir, gt, candidate, outdir, toolchain)
            else:
                pair_matched, pair_count, ttc, notes = replay_face(
                    family, tdir, gt, candidate, outdir, toolchain)
            dispatch = 1
            faces["replay"] = {"matched": pair_matched, "count": pair_count,
                               "toolchain": toolchain, "ttc_seconds": round(ttc, 3)}
            failures.extend(notes)
        except Skip as exc:
            failures.append({"code": "TOOLCHAIN_MISSING", "detail": str(exc)})
            faces["replay"] = {"toolchain": toolchain, "skipped": True}

    # ---- arithmetic verdict ----
    if any(f["code"] == "TOOLCHAIN_MISSING" for f in failures):
        verdict, rc = "SKIP", RC_SKIP
    elif verdict_kind:
        verdict = "PASS" if ok_face else "FAIL"
        rc = RC_PASS if ok_face else RC_FAIL
    else:
        ok, arith_failures = ds.arithmetic_verdict(
            hits=hits,
            min_constant_hits=thresholds.get("min_constant_hits", 0)
            if "constant-hit" in oracles else 0,
            pairs_matched=pair_matched,
            pair_count=pair_count if replay_armed else 0,
            min_pair_ratio=thresholds.get("min_pair_ratio", 1.0)
            if replay_armed else 1.0)
        failures.extend(arith_failures)
        verdict = "PASS" if ok else "FAIL"
        rc = RC_PASS if ok else RC_FAIL

    metrics = {
        "ttc_seconds": round(ttc, 3),
        "dispatch_count": dispatch,
        "pass_at_k_contribution": 1 if verdict == "PASS" else 0,
        "converged": 1 if verdict == "PASS" and not failures else 0,
    }
    if verdict_class is not None:
        metrics["verdict_class"] = verdict_class

    cand_digest = hashlib.sha256(candidate.read_bytes()).hexdigest()
    evidence = {
        "schema": ds.EVIDENCE_SCHEMA,
        "task_id": tdir.name,
        "eval_version": task["eval_version"],
        "family": family,
        "tier": task["tier"],
        "ts": ts,
        "candidate": str(candidate),
        "candidate_sha256": cand_digest,
        "faces": faces,
        "metrics": metrics,
        "verdict": verdict,
        "verdict_class": verdict_class,
        "failures": failures,
    }
    ev_path = outdir / (
        f"evidence-{tdir.name}-{time.strftime('%Y%m%dT%H%M%SZ')}-"
        f"{os.getpid() % 100000}.json")
    ev_path.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")

    # ---- the autoresearch.sh-style emission ----
    for name, value in metrics.items():
        print(ds.metric_line(name, value))
    for f in failures:
        print(f"FAILURE code={f['code']} detail={f['detail']}")
    print(f"EVIDENCE {ev_path}")
    print(f"VERDICT {verdict}")
    return rc, evidence


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="eval_checker.py",
        description="Mechanical checker for one #299 eval task (METRIC "
                    "emission, arithmetic verdict, evidence archive).")
    ap.add_argument("--task", required=True,
                    help="task id or task-unit directory")
    ap.add_argument("--tier", default=None,
                    choices=sorted(ds.TIERS),
                    help="tier to resolve a bare task id against (explicit task dirs bypass this)")
    ap.add_argument("--candidate", required=True,
                    help="candidate artifact (the arm's re-implementation; "
                         "self-check runs the constructed target itself)")
    ap.add_argument("--out", default=None,
                    help="evidence out-dir (default: runs/eval/<task_id>/)")
    args = ap.parse_args(argv)
    try:
        rc, _ = run(args.task, Path(args.candidate), args.out,
                    tier=args.tier)
    except Refusal as exc:
        print(f"FAILURE code={exc.code} detail={exc.detail}")
        print("VERDICT REFUSED")
        return RC_REFUSED
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
