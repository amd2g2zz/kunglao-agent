"""eval_checker.py — mechanical checker (the eval-dataset card).
Runner-style: the autoresearch.sh pattern.

Runs ONE eval task against ONE candidate artifact and produces
arithmetic-level evidence:

    METRIC <name>=<value>       the four contract metrics per task
    FAILURE code=<c> detail=... structured failure signals (enum in
                                eval_dataset.FAILURE_CODES)
    EVIDENCE <path>             the auto-archived evidence JSON
    VERDICT PASS|FAIL|SKIP|REFUSED

Exit contract: 0 PASS · 1 FAIL · 2 refusal (bad task/candidate) ·
3 SKIP (toolchain absent — CI degrades to a structured SKIP, never a
false FAIL).

Oracle faces (armed per task.yaml `checker.oracles`):
  constant-hit      static: the candidate's source must carry the variant's
                    mutated constants (hex or decimal, or the literal
                    hex-string form for key material) — memorizing the
                    canonical family constants scores zero by construction;
  pair-match        reproduction: a candidate program must reproduce the
                    captured pairs (the case-admission C2 threshold shape);
  replay-roundtrip  reproduction byte-exact over published PLUS
                    checker-minted probes (fresh inputs derived from the
                    variant seed — digest-table copying of the published
                    pairs fails by construction). Request families
                    (web-pack-sign/req-sign) replay object probes through
                    sign()/signRequest(); net-verify-license replays the
                    challenge/response protocol against a LOOPBACK-ONLY
                    mock license server hosted by this checker (no egress:
                    bind 127.0.0.1 ephemeral, base URL via argv, server-
                    side validation on published + minted challenges).

Evidence JSON (kunglao-eval-evidence/1) archives faces, metrics, verdict,
failures, and the candidate digest under the run out-dir (default
runs/eval/<task_id>/).

stdlib only.
"""
